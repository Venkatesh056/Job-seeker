"""Alembic environment.

Two decisions worth knowing:

  * **The URL comes from the application, not from alembic.ini.** `resolve_url()` is
    the single source of truth, so `alembic upgrade head` always targets the database
    the agent actually uses. A URL duplicated in a config file is one that will
    eventually disagree.
  * **`render_as_batch` is on.** SQLite cannot ALTER most column properties, so
    autogenerated migrations must use batch mode to be portable between the default
    SQLite and a Compose Postgres. Without it, a migration written against Postgres
    fails on the default backend.
"""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from careeragent.storage.db import resolve_url
from careeragent.storage.models import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata
config.set_main_option("sqlalchemy.url", resolve_url())


def _include_object(obj, name, type_, reflected, compare_to) -> bool:
    """Keep Alembic's own bookkeeping table out of autogenerated diffs."""
    return not (type_ == "table" and name == "alembic_version")


def run_migrations_offline() -> None:
    context.configure(
        url=resolve_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        render_as_batch=True,
        compare_type=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        render_as_batch=True,
        compare_type=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


async def _run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(_run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
